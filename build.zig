const std = @import("std");
const builtin = @import("builtin");

fn linkPlatformLibs(compile: *std.Build.Step.Compile, target: std.Build.ResolvedTarget) void {
    compile.root_module.link_libc = true;
    if (target.result.os.tag == .windows) {
        // Winsock symbols are provided by these system libraries on Windows.
        compile.root_module.linkSystemLibrary("ws2_32", .{});
        compile.root_module.linkSystemLibrary("mswsock", .{});
    }
}

/// Recursively embeds a directory into an executable at build time.
///
/// Walks `rootDir` (relative to the project root) with the host
/// filesystem, sorts entries deterministically by relative path, reads
/// every file, and generates a manifest module importable as
/// `importName`:
///
/// ```zig
/// const embedded = @import("embedWebsite");
/// try httpx.assets.registerEmbeddedDir(allocator, &embedded.files);
/// ```
///
/// `embedded.files` matches `httpx.assets.EmbeddedFile`
/// (`{ path, content }`), so one call registers the whole tree. Logical
/// paths are portable `/`-separated relatives and file bytes are inlined
/// as escaped string literals, keeping the generated manifest portable
/// across machines. MIME types and sizes derive at runtime through the
/// shared MIME system and `content.len` (single source of truth).
/// Asset names containing `"` and files over 16 MiB are skipped.
fn embedDir(b: *std.Build, exe: *std.Build.Step.Compile, httpxModule: *std.Build.Module, rootDir: []const u8, importName: []const u8) void {
    const allocator = b.allocator;
    var relPaths: std.ArrayList([]u8) = .empty;
    defer {
        for (relPaths.items) |p| allocator.free(p);
        relPaths.deinit(allocator);
    }

    const io = b.graph.io;
    const cwd: std.Io.Dir = .cwd();
    var root = cwd.openDir(io, rootDir, .{ .iterate = true }) catch return;
    defer root.close(io);
    var walker = root.walk(allocator) catch return;
    defer walker.deinit();
    while (walker.next(io) catch null) |entry| {
        if (entry.kind != .file) continue;
        var p = allocator.dupe(u8, entry.path) catch return;
        for (p, 0..) |_, i| {
            if (p[i] == '\\') p[i] = '/';
        }
        if (std.mem.indexOfScalar(u8, p, '"') != null) continue;
        relPaths.append(allocator, p) catch return;
    }
    std.mem.sort([]u8, relPaths.items, {}, struct {
        fn less(_: void, x: []u8, y: []u8) bool {
            return std.mem.order(u8, x, y) == .lt;
        }
    }.less);

    var out: std.ArrayList(u8) = .empty;
    defer out.deinit(allocator);
    out.print(allocator, "// Generated by build.zig embedDir from \"{s}\" - do not edit.\n", .{rootDir}) catch return;
    out.appendSlice(allocator, "const httpx = @import(\"httpx\");\n") catch return;
    out.appendSlice(allocator, "pub const files = [_]httpx.assets.EmbeddedFile{\n") catch return;
    for (relPaths.items) |rel| {
        const content = root.readFileAlloc(io, rel, allocator, .limited(16 * 1024 * 1024)) catch continue;
        defer allocator.free(content);
        out.print(allocator, "    .{{ .path = \"{s}\", .content = \"", .{rel}) catch return;
        for (content) |c| {
            switch (c) {
                '\n' => out.appendSlice(allocator, "\\n") catch return,
                '\r' => out.appendSlice(allocator, "\\r") catch return,
                '\t' => out.appendSlice(allocator, "\\t") catch return,
                0x20...0x7e => {
                    if (c == '"' or c == '\\') {
                        out.print(allocator, "\\{c}", .{c}) catch return;
                    } else {
                        out.append(allocator, c) catch return;
                    }
                },
                else => out.print(allocator, "\\x{x:0>2}", .{c}) catch return,
            }
        }
        out.appendSlice(allocator, "\" },\n") catch return;
    }
    out.appendSlice(allocator, "};\n") catch return;

    const wf = b.addWriteFiles();
    const manifestName = std.fmt.allocPrint(allocator, "{s}.zig", .{importName}) catch return;
    _ = wf.add(manifestName, out.items);
    exe.root_module.addAnonymousImport(importName, .{
        .root_source_file = wf.getDirectory().path(b, manifestName),
        .imports = &.{
            .{ .name = "httpx", .module = httpxModule },
        },
    });
}

