        .root_module = librootModule,
    });
    linkPlatformLibs(lib, target);

    b.installArtifact(lib);

    const docsStep = b.step("docs", "Generate library documentation");
    const installDocs = b.addInstallDirectory(.{
        .source_dir = lib.getEmittedDocs(),
        .install_dir = .prefix,
        .install_subdir = "docs",
    });
    docsStep.dependOn(&installDocs.step);

    const testAllStep = b.step("test-all", "Run tests, benchmarks, and all runnable examples");
    testAllStep.dependOn(testStep);
    testAllStep.dependOn(benchStep);
    testAllStep.dependOn(runAllExamples);
}
